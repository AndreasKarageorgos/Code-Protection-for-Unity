#if UNITY_EDITOR
using System.IO;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace CodeProtection.Editor
{

    /// Editor side owner of the settings asset. Keeps all UnityEditor calls out of
    /// the runtime ProtectionSettings type, finds the package wherever it was
    /// dropped, generates strong secrets and randomized markers so nothing ships
    /// with guessable or greppable names, writes the baked integrity secret, and
    /// writes the plain config file the compile time ILPostProcessor reads.

    public static class ProtectionSettingsEditor
    {
        const string ConfigRelPath = "ProjectSettings/CodeProtection.cfg";

        public static ProtectionSettings GetOrCreate()
        {
            if (ProtectionSettings.Instance != null) return ProtectionSettings.Instance;

            string root = PackageRoot();
            string assetPath = root + "/ProtectionSettings.asset";

            var settings = AssetDatabase.LoadAssetAtPath<ProtectionSettings>(assetPath);
            if (settings == null)
            {
                settings = ScriptableObject.CreateInstance<ProtectionSettings>();
                settings.metadataPassphrase = GenerateSecret();
                settings.integrityPassphrase = GenerateSecret();
                EnsureMarkers(settings);
                Directory.CreateDirectory(ToSystemPath(root));
                AssetDatabase.CreateAsset(settings, assetPath);
                AssetDatabase.SaveAssets();
                WriteIntegritySecret(settings);
                WriteConfig(settings);
            }
            else
            {
                EnsureMarkers(settings);
            }

            ProtectionSettings.Instance = settings;
            return settings;
        }

        /// Fill in any missing randomized markers, so the obfuscation never uses fixed names.
        public static void EnsureMarkers(ProtectionSettings s, bool force = false)
        {
            var rng = new System.Random();
            bool dirty = false;
            if (force || string.IsNullOrEmpty(s.decoderType)) { s.decoderType = Ident(rng, 8); dirty = true; }
            if (force || string.IsNullOrEmpty(s.decoderMethod)) { s.decoderMethod = Ident(rng, 4); dirty = true; }
            if (force || string.IsNullOrEmpty(s.fieldPrefix)) { s.fieldPrefix = Ident(rng, 3) + "_"; dirty = true; }
            if (force || string.IsNullOrEmpty(s.methodPrefix)) { s.methodPrefix = Ident(rng, 3) + "_"; dirty = true; }
            if (force || s.markerSalt == 0) { s.markerSalt = rng.Next(1, 0x10000); dirty = true; }
            if (force || string.IsNullOrEmpty(s.manifestFile) || s.manifestFile == "integrity.manifest.json")
            { s.manifestFile = Ident(rng, 10) + ".dat"; dirty = true; }
            if (dirty) EditorUtility.SetDirty(s);
        }

        public static string GenerateSecret()
        {
            byte[] bytes = new byte[24];
            using (var rng = RandomNumberGenerator.Create())
                rng.GetBytes(bytes);
            return System.Convert.ToBase64String(bytes).Replace('+', 'A').Replace('/', 'B').Replace("=", "");
        }

        public static bool IsPlaceholder(string value)
        {
            return string.IsNullOrEmpty(value)
                || value == ProtectionSettings.PlaceholderIntegrity
                || value == ProtectionSettings.PlaceholderMetadata
                || value == "change-me"
                || value == "change-me-integrity";
        }


        /// Rewrites IntegritySecret.generated.cs with the passphrase stored as a
        /// masked byte array, plus the randomized manifest filename, so neither the
        /// secret nor the manifest name is a plain, greppable constant.
        
        public static void WriteIntegritySecret(ProtectionSettings s)
        {
            byte[] utf8 = Encoding.UTF8.GetBytes(s.integrityPassphrase ?? "");
            const byte mask = 0x5A;
            var sb = new StringBuilder();
            for (int i = 0; i < utf8.Length; i++)
            {
                byte enc = (byte)(utf8[i] ^ mask ^ (byte)((i * 31 + 7) & 0xFF));
                if (i > 0) sb.Append(", ");
                sb.Append("0x").Append(enc.ToString("X2"));
            }

            string manifest = (s.manifestFile ?? "integrity.manifest.json").Replace("\\", "\\\\").Replace("\"", "\\\"");

            string content =
"namespace CodeProtection\n" +
"{\n" +
"    // AUTO GENERATED by the Code Protection panel. Do not edit by hand.\n" +
"    // Change the passphrase in Tools > Code Protection and press Save.\n" +
"    // Stored masked so a plain strings scan of the build does not reveal it.\n" +
"    public static class IntegritySecret\n" +
"    {\n" +
"        const byte Mask = 0x5A;\n" +
"        static readonly byte[] Data = { " + sb + " };\n" +
"        static string _value;\n" +
"\n" +
"        public const string ManifestFileName = \"" + manifest + "\";\n" +
"\n" +
"        public static string Value\n" +
"        {\n" +
"            get\n" +
"            {\n" +
"                if (_value != null) return _value;\n" +
"                var b = new byte[Data.Length];\n" +
"                for (int i = 0; i < Data.Length; i++)\n" +
"                    b[i] = (byte)(Data[i] ^ Mask ^ (byte)((i * 31 + 7) & 0xFF));\n" +
"                _value = System.Text.Encoding.UTF8.GetString(b);\n" +
"                return _value;\n" +
"            }\n" +
"        }\n" +
"    }\n" +
"}\n";

            string path = PackageRoot() + "/CodeGen/IntegritySecret.generated.cs";
            File.WriteAllText(ToSystemPath(path), content);
            AssetDatabase.ImportAsset(path);
            Debug.Log("[CodeProtection] IntegritySecret.generated.cs updated; Unity will recompile.");
        }

        
        /// Writes the plain key=value config the compile time ILPostProcessor reads.
        /// It lives under ProjectSettings so it is not imported as an asset.
        
        public static void WriteConfig(ProtectionSettings s)
        {
            EnsureMarkers(s);
            var sb = new StringBuilder();
            sb.Append("# Auto generated by Tools > Code Protection. Do not edit by hand.\n");
            sb.Append("addRandomCode=").Append(s.addRandomCode ? '1' : '0').Append('\n');
            sb.Append("obfuscateStrings=").Append(s.obfuscateStrings ? '1' : '0').Append('\n');
            sb.Append("forceAll=").Append(s.forceAll ? '1' : '0').Append('\n');
            sb.Append("junkMethodsPerType=").Append(s.junkMethodsPerType).Append('\n');
            sb.Append("injectDeadCalls=").Append(s.injectDeadCalls ? '1' : '0').Append('\n');
            sb.Append("minStringLength=").Append(s.minStringLength).Append('\n');
            sb.Append("excludeNamespaces=").Append(s.excludeNamespaces ?? "").Append('\n');
            sb.Append("decoderType=").Append(s.decoderType).Append('\n');
            sb.Append("decoderMethod=").Append(s.decoderMethod).Append('\n');
            sb.Append("fieldPrefix=").Append(s.fieldPrefix).Append('\n');
            sb.Append("methodPrefix=").Append(s.methodPrefix).Append('\n');
            sb.Append("salt=").Append(s.markerSalt).Append('\n');

            string projectRoot = Directory.GetParent(Application.dataPath).FullName;
            string full = Path.Combine(projectRoot, ConfigRelPath.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(full));
            File.WriteAllText(full, sb.ToString());
        }

        public static string PackageRoot()
        {
            foreach (var guid in AssetDatabase.FindAssets("XorKeystream t:MonoScript"))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid).Replace('\\', '/');
                if (p.EndsWith("/CodeGen/XorKeystream.cs"))
                    return p.Substring(0, p.Length - "/CodeGen/XorKeystream.cs".Length);
            }
            return "Assets/CodeProtection";
        }

        static string Ident(System.Random rng, int len)
        {
            const string first = "abcdefghijklmnopqrstuvwxyz";
            const string rest = "abcdefghijklmnopqrstuvwxyz0123456789";
            var buf = new char[len];
            buf[0] = first[rng.Next(first.Length)];
            for (int i = 1; i < len; i++) buf[i] = rest[rng.Next(rest.Length)];
            return new string(buf);
        }

        static string ToSystemPath(string assetPath)
        {
            string projectRoot = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(projectRoot, assetPath.Replace('/', Path.DirectorySeparatorChar));
        }
    }
}
#endif
